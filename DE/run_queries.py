"""Generate real query output from one PostgreSQL transaction that rolls back."""

from pathlib import Path

from app.postgres import connect, frame
from DE.queries import QUERIES

CASCADE_COUNTS = """
SELECT
 (SELECT count(*) FROM sensor_readings WHERE episode_id = %(episode)s) AS readings,
 (SELECT count(*) FROM predictions JOIN sensor_readings USING (reading_id)
  WHERE episode_id = %(episode)s) AS predictions,
 (SELECT count(*) FROM prediction_factors JOIN predictions USING (prediction_id)
  JOIN sensor_readings USING (reading_id) WHERE episode_id = %(episode)s) AS factors,
 (SELECT count(*) FROM alert_notifications WHERE alert_id = %(alert)s) AS notifications
"""


def fixture_episode(con, scenario):
    # Reserve a currently unused high seed in this transaction.
    return con.execute("""
        INSERT INTO simulation_episodes (scenario, seed, hours)
        SELECT %s, max(candidate), %s
        FROM generate_series(2147480000, 2147483647) AS candidate
        WHERE NOT EXISTS (
            SELECT 1 FROM simulation_episodes WHERE scenario = %s AND seed = candidate
        )
        RETURNING episode_id
    """, (scenario, 12 if scenario == "glof" else 1, scenario)).fetchone()["episode_id"]


def collect(con):
    con.execute("SELECT pg_advisory_xact_lock(610297)")
    episode = fixture_episode(con, "normal")
    glof = fixture_episode(con, "glof")
    con.execute("""
        WITH readings AS (
            INSERT INTO sensor_readings (lake_id, episode_id, hour, recorded_at, water_level_m)
            SELECT 'SL001', %s, h, timestamp '2024-08-01' + h * interval '1 hour', 12 + h / 10.0
            FROM generate_series(0, 11) h RETURNING reading_id, hour
        )
        INSERT INTO predictions (reading_id, model_id, level_id, risk_score)
        SELECT reading_id, 'capstone-v1', 2, 0.75 FROM readings
    """, (glof,))
    alert_sql = """
        INSERT INTO alerts (prediction_id, lake_id, level_id, sensor_time, risk_score, message, status)
        SELECT p.prediction_id, r.lake_id, 2, r.recorded_at::text, p.risk_score,
               'Illustrative warning', 'Illustrative preview'
        FROM predictions p JOIN sensor_readings r USING (reading_id)
        WHERE r.episode_id = %s AND r.hour = %s RETURNING alert_id
    """
    glof_alert = con.execute(alert_sql, (glof, 7)).fetchone()["alert_id"]
    report = ["# PostgreSQL query execution outputs",
              "Generated by `python -m DE.run_queries`. Synthetic demonstration rows and edits roll back. "
              "Existing rows may appear in read results. PostgreSQL identity sequences can advance."]
    for number, query in QUERIES.items():
        if number == "01":
            params = {"episode": episode}
        elif number in {"02", "03"}:
            params = {"alert": alert, "episode": episode}
        else:
            params = query.params
        report.append(f"## {number} {query.question}")
        if number == "03":
            report.extend(["Cascade counts before delete", code(frame(con, CASCADE_COUNTS, params))])
        report.append(code(frame(con, query.sql, params)))
        if number == "01":
            alert = con.execute(alert_sql, (episode, 0)).fetchone()["alert_id"]
            con.execute("""
                INSERT INTO alert_notifications (alert_id, recipient_id, channel, delivery_status)
                SELECT %s, recipient_id, 'telegram', 'Illustrative preview'
                FROM recipients WHERE seed_key IN ('demo-control', 'demo-liaison')
            """, (alert,))
            con.execute("""
                INSERT INTO alert_notifications (alert_id, recipient_id, channel, delivery_status)
                SELECT %s, recipient_id, 'telegram', 'Illustrative failed delivery'
                FROM recipients WHERE seed_key = 'demo-control'
            """, (glof_alert,))
        if number == "03":
            report.extend(["Cascade counts after delete", code(frame(con, CASCADE_COUNTS, params))])
    return "\n\n".join(report) + "\n"


def code(rows):
    return f"```text\n{rows.to_string(index=False)}\n```"


if __name__ == "__main__":
    with connect() as con:
        output = collect(con)
        con.rollback()
    path = Path(__file__).with_name("06_query_outputs.md")
    path.write_text(output)
    print(path)
